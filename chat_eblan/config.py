"""
Конфигурация проекта Chat_eblan (минимальная версия M0).

Единое место, где лежат ВСЕ настройки проекта. Остальные файлы
(model.py, train.py, tokenizer.py, data.py, chat.py) просто импортируют
эти переменные: `from config import BLOCK_SIZE, N_EMBD, ...`

Зачем вынести в отдельный файл:
- не надо менять гиперпараметры в 5 разных местах;
- чекпоинт хранит конфиг вместе с весами, поэтому модель можно
  загрузить даже если потом поменяли config.py.
"""

import torch

# ============================================================================
# УСТРОЙСТВО ВЫЧИСЛЕНИЙ (где крутятся матрицы)
# ============================================================================
# Порядок предпочтений:
#   1. "mps"  — Metal Performance Shaders, ускорение на Apple Silicon (M1/M2/M3/M4)
#   2. "cuda" — NVIDIA GPU (если вдруг запускаем на Linux/Windows с видеокартой)
#   3. "cpu"  — запасной вариант, медленно, но везде работает
# torch.backends.mps.is_available() проверяет, что Mac реально поддерживает MPS.
def _pick_device():
    if torch.backends.mps.is_available():
        return "mps"
    if torch.cuda.is_available():
        return "cuda"
    return "cpu"

DEVICE = _pick_device()

# ============================================================================
# ТОКЕНИЗАТОР (BPE из minbpe)
# ============================================================================
# VOCAB_SIZE — сколько BPE-мержей обучаем (НЕ итоговый размер словаря!).
# minbpe всегда начинает с 256 базовых байтов (0..255), и делает ровно
# (VOCAB_SIZE - 256) мержей поверх них. Плюс мы добавим 3 спецтокена чата.
# Итоговый размер словаря модели = VOCAB_SIZE + 3 (см. SPECIAL_TOKENS ниже).
# 512 => 256 мержей: маленький, но настоящий BPE (а не просто байты).
VOCAB_SIZE = 512

# Путь к обученному токенизатору (файлы .model и .vocab создаёт data.py)
TOKENIZER_PATH = "data/tokenizer"

# ============================================================================
# СПЕЦТОКЕНЫ ЧАТА ( special tokens )
# ============================================================================
# Это "магические" последовательности вида <|user|>, которые токенизатор
# НЕ разбивает на части, а выдаёт как ОДИН токен с фиксированным id.
# Благодаря им модель учится формату диалога:
#
#   <|user|>привет<|end|><|assistant|>привет<|end|><|user|>как дела?<|end|><|assistant|>...
#
# id спецтокенов ставим ПОСЛЕ всех обычных токенов, т.е. начиная с VOCAB_SIZE.
# Порядок важен: конвейер data.py -> tokenizer.py -> model.py использует их одинаково.
USER_TOKEN      = "<|user|>"       # начало реплики пользователя
ASSISTANT_TOKEN = "<|assistant|>"  # начало реплики ассистента (бота)
END_TOKEN       = "<|end|>"        # конец текущей реплики

# Словарь "строчка токена -> его id". Генерируется из VOCAB_SIZE,
# чтобы при смене VOCAB_SIZE id автоматически правильно пересчитались.
SPECIAL_TOKENS = {
    USER_TOKEN:      VOCAB_SIZE + 0,
    ASSISTANT_TOKEN: VOCAB_SIZE + 1,
    END_TOKEN:       VOCAB_SIZE + 2,
}

# Итоговый размер словаря, который увидит модель (обучаемые эмбеддинги + спецтокены)
VOCAB_SIZE_TOTAL = VOCAB_SIZE + len(SPECIAL_TOKENS)

# ============================================================================
# КОНТЕКСТ (сколько токенов модель "видит" за раз)
# ============================================================================
# BLOCK_SIZE = длина окна, которое модель рассматривает при предсказании.
# Учитывает и реплику пользователя, и начало ответа бота.
# Потом (M1) поднимем до 128-256, пока держим малым для быстрой проверки.
BLOCK_SIZE = 64

# ============================================================================
# АРХИТЕКТУРА ТРАНСФОРМЕРА
# ============================================================================
# N_EMBD — размерность вектора, в который превращается каждый токен.
# Каждый токен словаря кодируется вектором из N_EMBD чисел.
N_EMBD = 64

# N_HEAD — количество голов внимания (multi-head attention).
# Голова = один "взгляд" на контекст со своей проекцией Q/K/V.
# Важно, чтобы N_EMBD делился на N_HEAD: 64 / 4 = 16 — размер головы.
N_HEAD = 4

# N_LAYER — сколько Transformer-блоков (attention + feed-forward) друг на друге.
N_LAYER = 2

# DROPOUT — вероятность "выключить" нейрон на время обучения (регуляризация,
# чтобы модель не заучивала данные наизусть). 0.1 = 10% нейронов выключается.
DROPOUT = 0.1

# ============================================================================
# ОБУЧЕНИЕ
# ============================================================================
# BATCH_SIZE — сколько окон (по BLOCK_SIZE токенов) считаем за один шаг обучения.
BATCH_SIZE = 32

# LEARNING_RATE — скорость обучения AdamW. Слишком большая = расхождение,
# слишком маленькая = застревает на плохом решении.
LEARNING_RATE = 3e-4

# MAX_ITERS — сколько шагов обучения делаем всего.
MAX_ITERS = 1000

# EVAL_INTERVAL — каждые сколько итераций считаем loss на train и val.
EVAL_INTERVAL = 100

# EVAL_ITERS — сколько случайных батчей усредняем при оценке loss.
# Больше = оценка точнее, но медленнее.
EVAL_ITERS = 20

# SEED — зерно генератора случайных чисел. С одинаковым seed инициализация
# весов воспроизводима — удобно для отладки.
SEED = 1337

# ============================================================================
# ПУТИ К ФАЙЛАМ (относительно chat_eblan/ — запускать скрипты оттуда!)
# ============================================================================
DATA_DIR = "data"                        # сюда кладём .bin и .vocab
TRAIN_BIN = "data/train.bin"             # обучающие токены (uint16)
VAL_BIN = "data/val.bin"                 # валидационные токены (uint16)
CKPT_DIR = "checkpoints"                 # сюда кладём веса модели
CKPT_PATH = "checkpoints/ckpt.pt"        # основной чекпоинт (модель + конфиг + итерация)
