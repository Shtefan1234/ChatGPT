"""
Подготовка данных для обучения (мини-версия M0).

Здесь:
1) лежит МИНИ-КОРПУС диалогов (заглушка вместо реальных переписок из ТГ);
2) корпус приводится к формату чата:
      <|user|>текст<|end|><|assistant|>ответ<|end|>
3) обучается BPE-токенизатор на этом корпусе и сохраняется в data/tokenizer.model;
4) весь текст кодируется в токены и сохраняется в data/train.bin и data/val.bin
   (по uint16 на токен, потому что словарь < 65536).

Запуск:  python data.py   (из папки chat_eblan/)

Потом (M1) этот файл заменим парсером реального экспорта Telegram (result.json),
но формат выхода (.bin + tokenizer.model) останется тем же — train.py не тронем.
"""

import os
import numpy as np

import config
from tokenizer import ChatTokenizer


# ---------------------------------------------------------------------------
# МИНИ-КОРПУС (заглушка). Каждый элемент — пара (реплика_юзера, ответ_бота).
# Когда появятся реальные переписки из ТГ, этот список удалим и будем читать JSON.
# ---------------------------------------------------------------------------
DIALOGUES = [
    ("привет", "привет! как дела?"),
    ("привет", "здравствуй! чем могу помочь?"),
    ("как дела?", "отлично, спасибо! у тебя как?"),
    ("как дела?", "нормально, работаю. а у тебя?"),
    ("что делаешь?", "пишу код и учусь. а ты?"),
    ("пока", "пока! до связи."),
    ("пока", "до встречи! хорошего дня."),
    ("спасибо", "не за что!"),
    ("спасибо", "пожалуйста!"),
    ("пожалуйста", "рад помочь."),
    ("как тебя зовут?", "меня зовут чат-еблан."),
    ("кто ты?", "я маленькая нейросеть для чата."),
    ("что умеешь?", "умею отвечать на простые вопросы."),
    ("где ты?", "я живу в твоем компьютере."),
    ("что нового?", "ничего особенного, просто учусь."),
    ("хорошо", "отлично!"),
    ("плохо", "ой, что случилось?"),
    ("спокойной ночи", "спокойной ночи! спи хорошо."),
    ("доброе утро", "доброе утро! как настроение?"),
    ("до завтра", "до завтра! пока."),
]

# Сколько раз повторяем мини-корпус, чтобы набрать побольше токенов.
# Для M0 этого достаточно (модель выучит простые закономерности, loss упадёт).
# В M1 заменим на реальные переписки из ТГ — повторы больше не нужны.
REPEAT = 20


def build_dialog_text() -> str:
    """
    Склеивает все пары в один большой текст в формате чата.

    Каждая реплика оборачивается в спецтокены:
      <|user|>...<|end|>  и  <|assistant|>...<|end|>
    Модель учится предсказывать ответ бота после <|assistant|>.
    """
    parts = []
    for _ in range(REPEAT):
        for user_msg, bot_msg in DIALOGUES:
            parts.append(f"{config.USER_TOKEN}{user_msg}{config.END_TOKEN}")
            parts.append(f"{config.ASSISTANT_TOKEN}{bot_msg}{config.END_TOKEN}")
    # склеиваем без пробелов между диалогами — конец реплики уже помечен <|end|>
    return "".join(parts)


def main():
    os.makedirs(config.DATA_DIR, exist_ok=True)

    # 1) собрать текст корпуса
    text = build_dialog_text()
    print(f"[data] длина корпуса: {len(text)} символов, пар: {len(DIALOGUES) * REPEAT}")

    # 2) обучить BPE-токенизатор и сохранить его
    print("[data] обучаем BPE-токенизатор...")
    tok = ChatTokenizer()
    tok.train(text, verbose=False)  # verbose=True — печатать каждый мерж
    tok.save(config.TOKENIZER_PATH)
    print(f"[data] токенизатор сохранён: {config.TOKENIZER_PATH}.model / .vocab")

    # 3) закодировать весь корпус в один поток токенов
    ids = tok.encode(text)
    print(f"[data] корпус = {len(ids)} токенов, vocab_size = {tok.vocab_size}")

    # 4) разделить на train (90%) и val (10%) и сохранить в .bin (uint16)
    data = np.array(ids, dtype=np.uint16)
    n = int(0.9 * len(data))
    train_data = data[:n]
    val_data = data[n:]

    train_data.tofile(config.TRAIN_BIN)
    val_data.tofile(config.VAL_BIN)
    print(f"[data] train.bin: {len(train_data)} токенов")
    print(f"[data] val.bin:   {len(val_data)} токенов")
    print("[data] Готово. Теперь запускай: python train.py")


if __name__ == "__main__":
    main()
